/**
 * Intelligent matcher that returns the most accurate Stitch food photography URL
 * for any dish, order, menu item, or food type.
 */
export function getFoodImage(name = '', foodType = '', mealType = '') {
  const q = `${name} ${foodType} ${mealType}`.toLowerCase();

  // 1. Specific Paneer variations
  if (q.includes('palak paneer') || q.includes('saag paneer')) {
    return STITCH_FOOD_ASSETS.PALAK_PANEER;
  }
  if (q.includes('matar paneer') || q.includes('aloo matar') || q.includes('mutter paneer')) {
    return STITCH_FOOD_ASSETS.MATAR_PANEER;
  }
  if (q.includes('paneer tikka') || q.includes('tikka')) {
    return STITCH_FOOD_ASSETS.PANEER_TIKKA;
  }
  if (q.includes('shahi paneer') || q.includes('paneer butter') || q.includes('paneer kolhapuri') || q.includes('paneer masala') || q.includes('paneer')) {
    return STITCH_FOOD_ASSETS.PANEER_BUTTER_MASALA;
  }

  // 2. Dal & Lentils & Khichdi
  if (q.includes('dal fry') || q.includes('dal tadka') || q.includes('dal makhani') || q.includes('yellow dal') || q.includes('varan') || q.includes('khichdi') || q.includes('kadhi') || q.includes('dal')) {
    return STITCH_FOOD_ASSETS.DAL_KHICHDI;
  }

  // 3. Bread & Roti & Poli & Bhakri
  if (q.includes('phulka') || q.includes('roti') || q.includes('chapati') || q.includes('poli') || q.includes('bhakri') || q.includes('paratha')) {
    return STITCH_FOOD_ASSETS.ROTI_PHULKA;
  }

  // 4. Rice & Biryani & Pulao
  if (q.includes('rice') || q.includes('jeera rice') || q.includes('steamed rice') || q.includes('biryani') || q.includes('pulao') || q.includes('bhaat') || q.includes('dum')) {
    return STITCH_FOOD_ASSETS.BIRYANI;
  }

  // 5. Sev Sabji / Tamatar
  if (q.includes('sev') || q.includes('shev')) {
    return STITCH_FOOD_ASSETS.SHEV_BHAJI;
  }

  // 6. Potato & Gobi & Batata
  if (q.includes('batata') || q.includes('aloo gobi') || q.includes('gobi') || q.includes('flower') || q.includes('aloo')) {
    return STITCH_FOOD_ASSETS.ALOO_GOBI;
  }

  // 7. Chicken & Non-Veg Dishes
  if (q.includes('chicken 65') || q.includes('crispy chicken')) {
    return STITCH_FOOD_ASSETS.CHICKEN_65;
  }
  if (q.includes('chicken thali') || (q.includes('chicken') && q.includes('thali'))) {
    return STITCH_FOOD_ASSETS.CHICKEN_THALI;
  }
  if (q.includes('chicken') || q.includes('murgh') || q.includes('tambda') || q.includes('rassa') || q.includes('sukka')) {
    return STITCH_FOOD_ASSETS.CHICKEN_CURRY;
  }
  if (q.includes('mutton') || q.includes('meat') || q.includes('gosht')) {
    return STITCH_FOOD_ASSETS.MUTTON_CURRY;
  }
  if (q.includes('egg') || q.includes('anda')) {
    return STITCH_FOOD_ASSETS.EGG_CURRY;
  }
  if (q.includes('fish') || q.includes('pomfret') || q.includes('paplet') || q.includes('prawn')) {
    return STITCH_FOOD_ASSETS.FISH_FRY;
  }

  // 8. Other Specific Sabjis
  if (q.includes('kaju') || q.includes('cashew')) {
    return STITCH_FOOD_ASSETS.KAJU_CURRY;
  }
  if (q.includes('pithla') || q.includes('pitla') || q.includes('thecha')) {
    return STITCH_FOOD_ASSETS.PITHLA_BHAKRI;
  }
  if (q.includes('baingan') || q.includes('vangi') || q.includes('bharta')) {
    return STITCH_FOOD_ASSETS.BAINGAN_BHARTA;
  }
  if (q.includes('bhindi') || q.includes('okra') || q.includes('ladyfinger')) {
    return STITCH_FOOD_ASSETS.BHINDI_MASALA;
  }
  if (q.includes('gavar') || q.includes('cluster')) {
    return STITCH_FOOD_ASSETS.GAVAR_BHAJI;
  }
  if (q.includes('chole') || q.includes('chana') || q.includes('bhature')) {
    return STITCH_FOOD_ASSETS.CHOLE_MASALA;
  }
  if (q.includes('matki') || q.includes('usal') || q.includes('sprout')) {
    return STITCH_FOOD_ASSETS.MATKI_USAL;
  }
  if (q.includes('saag') || q.includes('methi') || q.includes('palak')) {
    return STITCH_FOOD_ASSETS.PALAK_SAAG;
  }
  if (q.includes('mix veg') || q.includes('jalfrezi') || q.includes('handi')) {
    return STITCH_FOOD_ASSETS.MIX_VEG;
  }

  // Default to Royal Veg Thali
  return STITCH_FOOD_ASSETS.ROYAL_VEG_THALI;
}

/**
 * Returns signature banner photography for Provider Kitchen Cards
 */
export function getProviderBannerImage(provider) {
  if (!provider) return STITCH_FOOD_ASSETS.ROYAL_VEG_THALI;
  
  const name = (provider.kitchen_name || provider.provider_name || '').toLowerCase();
  const bio = (provider.bio || '').toLowerCase();
  const fType = (provider.food_type || '').toLowerCase();

  if (fType.includes('non-veg') || name.includes('anita') || name.includes('non veg') || name.includes('chicken')) {
    return STITCH_FOOD_ASSETS.CHICKEN_THALI;
  }
  if (name.includes('sarita') || name.includes('maa ki rasoi') || bio.includes('maharashtrian') || bio.includes('poli')) {
    return STITCH_FOOD_ASSETS.ROYAL_VEG_THALI;
  }
  if (name.includes('radha') || name.includes('annapurna') || name.includes('satvik')) {
    return STITCH_FOOD_ASSETS.PANEER_BUTTER_MASALA;
  }
  if (fType.includes('both')) {
    return STITCH_FOOD_ASSETS.BIRYANI;
  }
  return STITCH_FOOD_ASSETS.ROYAL_VEG_THALI;
}
